// Writes src/lib/templates/catalog/generated.ts: one import per template file in
// src/lib/templates/catalog/templates/ and `ALL`, sorted by id. Runs before dev and build
// (predev/prebuild) and via `npm run gen:templates`. No dependencies; only rewrites the file
// when its content changes. generated.ts is gitignored, so parallel template authors never
// conflict on it.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalogDir = join(root, "src", "lib", "templates", "catalog");
const templatesDir = join(catalogDir, "templates");
const outFile = join(catalogDir, "generated.ts");

const KEBAB = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const ids = readdirSync(templatesDir)
  .filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts"))
  .map((f) => f.slice(0, -3))
  .sort();

const bad = ids.filter((id) => !KEBAB.test(id));
if (bad.length) {
  console.error(`gen-templates: template file names must be kebab-case ids: ${bad.map((b) => b + ".ts").join(", ")}`);
  process.exit(1);
}

const ident = (id) => "t_" + id.replace(/-/g, "_");
const out = [
  "// GENERATED by scripts/gen-templates.mjs from catalog/templates/. Do not edit or commit.",
  'import type { Template } from "./types";',
  ...ids.map((id) => `import ${ident(id)} from "./templates/${id}";`),
  "",
  "export const ALL: Template[] = [",
  ...ids.map((id) => `  ${ident(id)},`),
  "];",
  "",
  "/** File name (without .ts) of each entry in ALL, so index.ts can check it matches the id. */",
  `export const FILE_IDS: string[] = ${JSON.stringify(ids)};`,
  "",
].join("\n");

let current = null;
try {
  current = readFileSync(outFile, "utf8");
} catch {}
if (current !== out) {
  writeFileSync(outFile, out);
  console.log(`gen-templates: wrote ${ids.length} templates to src/lib/templates/catalog/generated.ts`);
} else {
  console.log(`gen-templates: ${ids.length} templates, generated.ts up to date`);
}
